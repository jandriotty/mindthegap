import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../dist/app.js',import.meta.url),'utf8');
const data=JSON.parse(fs.readFileSync(new URL('../dist/data/demo.json',import.meta.url),'utf8'));
const context=vm.createContext({Date,console});
vm.runInContext(source.slice(0,source.indexOf('function render(){'))+'\nthis.testApi={band,reasons,needs};',context);
const {band,reasons,needs}=context.testApi;
const count=Object.fromEntries(['unresolved','review','confirmed'].map(b=>[b,data.clients.filter(c=>band(c)===b).length]));
assert.deepEqual(count,{unresolved:4,review:4,confirmed:4});
const c=structuredClone(data.clients[0]);
c.tasks.forEach(t=>t.status='Accepted');assert.equal(band(c),'unresolved','Accepted referral must remain unresolved');
c.tasks.forEach(t=>t.status='Support verified');c.cooling.value='working';c.transport.value='no';assert.equal(band(c),'confirmed');
c.outcome='Unreachable';assert.equal(band(c),'review','Unreachable must not be confirmed');
c.outcome='';c.consent.value='unknown';assert.equal(band(c),'review','Unknown permission remains review');
c.consent.value='yes';c.cooling.verified_at=null;assert.equal(needs(c,'cooling'),true);assert.equal(band(c),'review');
c.cooling.value='broken';assert.equal(band(c),'unresolved','New cooling failure reopens priority');
assert.ok(reasons(c).some(r=>r.includes('Cooling')));
assert.equal(data.hvi_total_rows,198);assert.equal(data.heat.length,153);assert.ok(data.clients.every(c=>c.synthetic));
console.log('PASS: group counts, accepted-vs-verified support, unreachable, consent, stale data, reopened need, public data and synthetic labeling.');
